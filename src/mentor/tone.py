FALLBACK: str = "今天记下了。"


def _compact(text: str) -> str:
    return re.sub(r"\s+", "", text).lower()


def banned_hits(text: str) -> list[str]:
    """text 里出现了哪些禁用说法（忽略空格和大小写，所以「作为一个 AI」也算）。"""
    compact = _compact(text)
    return [phrase for phrase, _, _ in BANNED if _compact(phrase) in compact]


def speak(generate: Callable[[], str], fallback: str = FALLBACK) -> str:
    """生成一句给用户看的话：命中禁用说法就重来一次，还命中就用兜底句，不报错。"""
    for _ in range(2):
        text = generate()
        if not banned_hits(text):
            return text
    return fallback


def quote_is_verbatim(quote: str, message: str) -> bool:
    """quote 是不是 message 里一字不差的连续片段。空的、只有空白的不算引用。"""
    return bool(quote.strip()) and quote in message
